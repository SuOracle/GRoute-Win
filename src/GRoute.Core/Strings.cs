    {
        Lang.Fa => "Vazirmatn, Tahoma, Segoe UI",
        Lang.Zh => "Microsoft YaHei UI, Microsoft YaHei, Segoe UI",
        Lang.Ru => "Segoe UI, Tahoma",
        _ => ""
    };

    public static string Get(Lang lang, string key)
    {
        var map = lang switch
        {
            Lang.Fa => Fa,
            Lang.Ru => Ru,
            Lang.Zh => Zh,
            _ => En
        };
        if (map.TryGetValue(key, out var v)) return v;
        return En.TryGetValue(key, out var e) ? e : key;
    }
